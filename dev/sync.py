#!/usr/bin/env python3
"""Regenerates everything derived from the plugins, so nothing drifts:

- shared/hooks/domains.txt: one line per domain, read by the hooks;
- each plugin's hooks/lib.sh, context.sh and domains.txt: copies of shared/hooks/ (a plugin can't read another's files);
- the domains table in README.md, the architecture table in CLAUDE.md and the skills table in each
  plugins/<domain>/README.md, between catalog markers;
- plugins/core/skills/skills/catalog.md: every domain and skill with its switch, for /core:skills.

Sources: .claude-plugin/marketplace.json (the domains, in order), each plugin.json (description, dependencies) and each
skill's SKILL.md frontmatter (name, description).

Usage: python3 dev/sync.py          rewrite what is out of date
       python3 dev/sync.py --check  write nothing; list what is out of date and exit 1 if anything is
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHARED = os.path.join(ROOT, "shared", "hooks")
SHARED_FILES = ["lib.sh", "context.sh", "domains.txt"]
READ_RULE = "Read(~/.claude/plugins/cache/*/{}/**)"


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def frontmatter(path):
    text = read(path)
    if not text.startswith("---\n"):
        raise SystemExit(f"{path}: no frontmatter")
    fields = {}
    for line in text[4:text.index("\n---", 4)].splitlines():
        match = re.match(r"^([a-z-]+):\s*(.*)$", line)
        if match:
            fields[match.group(1)] = match.group(2).strip()
    return fields


def upper(name):
    return name.upper().replace("-", "_")


def load():
    market = json.loads(read(os.path.join(ROOT, ".claude-plugin", "marketplace.json")))
    names = [p["name"] for p in market["plugins"]]
    domains = []
    for entry in market["plugins"]:
        folder = os.path.normpath(os.path.join(ROOT, entry["source"]))
        manifest = json.loads(read(os.path.join(folder, ".claude-plugin", "plugin.json")))
        deps = []
        for dep in manifest.get("dependencies", []):
            dep = dep if isinstance(dep, str) else dep["name"]
            if "@" not in dep and dep in names:
                deps.append(dep)
        skills = []
        skills_dir = os.path.join(folder, "skills")
        for skill in sorted(os.listdir(skills_dir)):
            path = os.path.join(skills_dir, skill, "SKILL.md")
            if not os.path.isfile(path):
                continue
            fields = frontmatter(path)
            if fields.get("name") != skill:
                raise SystemExit(f"{path}: name '{fields.get('name')}' doesn't match its folder")
            skills.append({"name": skill, "description": fields.get("description", "")})
        if not any(s["name"] == "standards" for s in skills):
            raise SystemExit(f"{entry['name']}: every domain needs a standards skill")
        # A hub row's first ../<skill>/ link is the skill it belongs to; another skill linked after it is one it needs.
        skill_names = {s["name"] for s in skills}
        needs = {}
        for line in read(os.path.join(skills_dir, "standards", "SKILL.md")).splitlines():
            if not line.startswith("|"):
                continue
            linked = [n for n in re.findall(r"\]\(\.\./([a-z0-9-]+)/", line) if n in skill_names]
            for other in linked[1:]:
                if other != linked[0] and other not in needs.setdefault(linked[0], []):
                    needs[linked[0]].append(other)
        for skill in skills:
            skill["needs"] = needs.get(skill["name"], [])
        domains.append({
            "name": entry["name"],
            "folder": folder,
            "description": manifest.get("description", ""),
            "deps": deps,
            "skills": skills,
        })
    return domains


def check_cycles(domains):
    deps = {d["name"]: d["deps"] for d in domains}

    def visit(name, path):
        if name in path:
            raise SystemExit("domains build on each other in a cycle: " + " -> ".join(path + [name]))
        for dep in deps.get(name, []):
            visit(dep, path + [name])

    for name in deps:
        visit(name, [])


def switch(domain, skill=None):
    if skill is None or skill == "standards":
        return f"{upper(domain)}_STANDARDS"
    return f"{upper(domain)}_SKILL_{upper(skill)}"


def builders(domains, name):
    return [d["name"] for d in domains if name in d["deps"]]


def domains_txt(domains):
    lines = ["# domain|PREFIX|domains it builds on|skill=SKILL ... (generated by dev/sync.py from the plugins: don't edit)"]
    for d in domains:
        pairs = " ".join(f"{s['name']}={upper(s['name'])}" for s in d["skills"] if s["name"] != "standards")
        lines.append(f"{d['name']}|{upper(d['name'])}|{' '.join(d['deps'])}|{pairs}")
    return "\n".join(lines) + "\n"


def cell(text):
    return text.replace("|", "\\|")


def domains_table(domains):
    rows = ["| Domain | What it covers | Comes on with | Switch |", "|---|---|---|---|"]
    for d in domains:
        comes = ", ".join(builders(domains, d["name"])) or "-"
        rows.append(f"| [{d['name']}](plugins/{d['name']}/README.md) | {cell(d['description'])} | {comes} | `{switch(d['name'])}` |")
    return "\n".join(rows)


def architecture_table(domains):
    rows = ["| Domain | Builds on | Skills |", "|---|---|---|"]
    for d in domains:
        skills = ", ".join(s["name"] for s in d["skills"])
        rows.append(f"| [{d['name']}](plugins/{d['name']}/README.md) | {', '.join(d['deps']) or '-'} | {skills} |")
    return "\n".join(rows)


def skills_table(d):
    rows = ["| Skill | Command | What it does | Switch |", "|---|---|---|---|"]
    for s in d["skills"]:
        rows.append(f"| [{s['name']}](skills/{s['name']}/SKILL.md) | `/{d['name']}:{s['name']}` | {cell(s['description'])} | `{switch(d['name'], s['name'])}` |")
    return "\n".join(rows)


def catalog(domains):
    out = [
        "# Catalog",
        "",
        "Every domain and skill of this marketplace, with the switch that turns it on in a project. A skill works only with "
        "the skills it needs on. Generated by `dev/sync.py` from the plugins: don't edit.",
        "",
    ]
    for d in domains:
        comes = ", ".join(builders(domains, d["name"]))
        out += [
            f"## {d['name']}",
            "",
            d["description"],
            "",
            f"- Switch: `{switch(d['name'])}`. Read rule: `{READ_RULE.format(d['name'])}`.",
            f"- Builds on: {', '.join(d['deps']) or 'nothing'}." + (f" Comes on with: {comes}." if comes else ""),
            "",
            "| Skill | Does | Needs | Switch |",
            "|---|---|---|---|",
        ]
        for s in d["skills"]:
            if s["name"] == "standards":
                continue
            needs = ", ".join(f"`{d['name']}:{n}`" for n in s["needs"]) or "-"
            out.append(f"| `{d['name']}:{s['name']}` | {cell(s['description'])} | {needs} | `{switch(d['name'], s['name'])}` |")
        out.append("")
    return "\n".join(out)


def between(text, marker, body, path):
    start, end = f"<!-- catalog:{marker} -->", "<!-- /catalog -->"
    if start not in text:
        raise SystemExit(f"{path}: missing {start}")
    head, rest = text.split(start, 1)
    if end not in rest:
        raise SystemExit(f"{path}: missing {end} after {start}")
    tail = rest.split(end, 1)[1]
    return f"{head}{start}\n{body}\n{end}{tail}"


def main():
    check = "--check" in sys.argv[1:]
    domains = load()
    check_cycles(domains)
    wanted = {os.path.join(SHARED, "domains.txt"): domains_txt(domains)}

    readme = os.path.join(ROOT, "README.md")
    wanted[readme] = between(read(readme), "domains", domains_table(domains), readme)
    claude_md = os.path.join(ROOT, "CLAUDE.md")
    wanted[claude_md] = between(read(claude_md), "architecture", architecture_table(domains), claude_md)
    for d in domains:
        path = os.path.join(d["folder"], "README.md")
        if not os.path.isfile(path):
            raise SystemExit(f"{path}: every domain needs a README.md")
        wanted[path] = between(read(path), "skills", skills_table(d), path)
    core = next(d for d in domains if d["name"] == "core")
    wanted[os.path.join(core["folder"], "skills", "skills", "catalog.md")] = catalog(domains)

    for name in SHARED_FILES:
        source = os.path.join(SHARED, name)
        body = wanted.get(source) or read(source)
        for d in domains:
            wanted[os.path.join(d["folder"], "hooks", name)] = body

    stale = []
    for path, body in wanted.items():
        current = read(path) if os.path.isfile(path) else None
        if current == body:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(body)

    if check:
        if stale:
            print("Out of date (run python3 dev/sync.py):\n  " + "\n  ".join(stale))
            sys.exit(1)
    elif stale:
        print("Updated:\n  " + "\n  ".join(stale))


if __name__ == "__main__":
    main()
